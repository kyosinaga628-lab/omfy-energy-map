  const keyOf = (claim) => String(claim).replace(/\s/g, '').slice(0, 22);

  // 意見に tags（axis/tech/actor/kw/life）を付ける。手で付けたタグがあればそれ、無ければ論点から推定
  function enrich(data) {
    const ops = data.opinions.filter((o) => !/^test/i.test(o.claim));
    ops.forEach((o, i) => {
      o.idx = i;
      const node = data.tree.byLabel[o.nodeLabel];
      const path = node ? O.pathOf(node) : [];
      // 旧 4 階層目（問い）の論点名はキーワードとして必ず付ける
      const kwFromNode = node && node.kind === '問い' ? [KW_ALIAS[node.label] || node.label] : [];
      const t = TAGS[keyOf(o.claim)];
      if (t) {
        o.tags = { axis: t[0], tech: t[1], actor: t[2], kw: uniq(kwFromNode.concat(t[3])), life: t[4] };
        o.auto = false;
      } else {
        const tech = uniq(path.map((n) => TECH_NODE[n.id]).filter(Boolean));
        let axis = uniq(path.map((n) => AXIS_NODE[n.id]).filter(Boolean));
        if (node) Object.keys(AXIS_FLAG).forEach((c) => { if (node.flags[c]) axis.push(AXIS_FLAG[c]); });
        o.tags = { axis: uniq(axis), tech: tech.length ? tech : ['X'], actor: [], kw: kwFromNode, life: [] };
        o.auto = true;
      }
      o.node = node || null;
      o.ext = path.some((n) => n.id === 'intl') ? 'intl' : path.some((n) => n.id === 'dom') ? 'dom' : '';
    });
    return ops;
  }
  function uniq(a) { return Array.from(new Set(a)); }

  // 軸の値の一覧（その軸のタグが無い意見は none 扱い）
  function valuesOf(o, facet) {
    const v = o.tags[facet];
    return v && v.length ? v : ['_'];
  }
  function valueLabel(facet, v) { return v === '_' ? FACETS[facet].none : FACETS[facet].label[v] || v; }

  // 意見カード（common.js の opinionHtml にタグの行を足したもの）
  function opCardHtml(o, opts) {
    opts = opts || {};
    const e = O.escapeHtml;
    const c = O.stanceColor(o.stance);
    const chips = [];
    ['axis', 'tech', 'actor'].forEach((f) => o.tags[f].forEach((v) => {
      if (f === 'tech' && v === 'X') return;
      chips.push('<span class="tg tg-' + f + '">' + e(valueLabel(f, v)) + '</span>');
    }));
    o.tags.kw.forEach((k) => chips.push('<button type="button" class="tg tg-kw' + (opts.kw === k ? ' on' : '') + '" data-kw="' + e(k) + '">#' + e(k) + '</button>'));
    return '<div class="op" data-op="' + o.idx + '">' +
      '<div class="claim">' + e(o.claim) + '</div>' +
      (o.note ? '<div class="note">' + e(o.note) + '</div>' : '') +
      '<div class="tgs">' + chips.join('') + (o.auto ? '<span class="tg tg-auto">タグは論点から自動推定</span>' : '') + '</div>' +
      '<div class="meta2">' +
        '<span class="st" style="background:color-mix(in srgb, ' + c + ' 16%, var(--surface));color:' + c + '">' + e(o.stance || '立場未記入') + '</span>' +
        '<span>根拠: ' + e(o.basis || '未記入') + '</span>' +
        (o.node ? '<a href="detail.html#n=' + encodeURIComponent(o.node.id) + '">論点: ' + e(o.nodeLabel) + '</a>' : '') +
        '<span class="au">' + e(o.handle) + '</span>' +
      '</div></div>';
  }

  function count(list, fn) {
    const m = new Map();
    list.forEach((x) => fn(x).forEach((k) => m.set(k, (m.get(k) || 0) + 1)));
    return m;
  }

